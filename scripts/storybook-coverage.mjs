// Maps the application's reusable components to their Storybook stories, and lists what has none. No Storybook install needed: it reads the
// source tree and the story files as text.
//   node scripts/storybook-coverage.mjs            prints the map and the gaps; exit 1 when a component has neither a story nor an exclusion
//   node scripts/storybook-coverage.mjs --write    also (re)writes storybook/COVERAGE.md
// A component with no story must be listed, with a reason, in storybook/coverage-exclusions.json (path relative to the repository root).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = (p) => path.relative(ROOT, p).split(path.sep).join('/');

/** The directories whose components are the app's reusable library. Each file that exports a React component needs a story. The design-system components (src/components/ui and the field primitives) live in dxp-ui (dxp-ui-library) and are covered by ITS Storybook. */
const LIBRARY_DIRS = ['src/components/primitives', 'src/components/domain', 'src/components/patterns', 'src/components/patterns/wizard', 'src/capabilities'];

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const f of fs.readdirSync(dir)) {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

/** Exported React components of a file: `export function Name` / `export const Name = (` / `export default function Name`, capitalised. */
function exportedComponents(file) {
  const text = fs.readFileSync(file, 'utf8');
  const names = new Set();
  for (const m of text.matchAll(/export\s+(?:default\s+)?function\s+([A-Z]\w*)/g)) names.add(m[1]);
  for (const m of text.matchAll(/export\s+const\s+([A-Z]\w*)\s*(?::[^=]+)?=\s*(?:\(|memo\(|forwardRef|React\.)/g)) names.add(m[1]);
  return [...names];
}

export function componentFiles() {
  const files = new Set();
  for (const d of LIBRARY_DIRS) {
    for (const f of walk(path.join(ROOT, d))) {
      if (!/\.tsx$/.test(f) || /\.(stories|test)\.tsx$/.test(f)) continue;
      // Capabilities: only the component files, not previews/demos (those are the app's own library page).
      if (d === 'src/capabilities' && /previewDemos|previews\.tsx$/.test(f)) continue;
      if (exportedComponents(f).length) files.add(rel(f));
    }
  }
  return [...files].sort();
}

export function storyFiles() {
  return walk(path.join(ROOT, 'storybook')).filter((f) => /\.stories\.tsx?$|\.mdx$/.test(f)).map(rel).sort();
}

/** Names imported by a story file (`import { A, B as C } from ...`, default imports included). */
function importedNames(text) {
  const names = new Set();
  for (const m of text.matchAll(/import\s+(?:type\s+)?([^;]*?)\s+from\s+['"][^'"]+['"]/gs)) {
    for (const n of m[1].matchAll(/([A-Za-z_$][\w$]*)(?:\s+as\s+[A-Za-z_$][\w$]*)?/g)) names.add(n[1]);
  }
  return names;
}

/** component file -> the story files that import one of its exported components (by name, so a re-export through a capability barrel counts). */
export function coverage() {
  const stories = storyFiles().map((f) => ({ file: f, names: importedNames(fs.readFileSync(path.join(ROOT, f), 'utf8')) }));
  const exclusions = JSON.parse(fs.readFileSync(path.join(ROOT, 'storybook/coverage-exclusions.json'), 'utf8'));
  const map = {};
  for (const comp of componentFiles()) {
    const exported = exportedComponents(path.join(ROOT, comp));
    const used = stories.filter(({ names }) => exported.some((n) => names.has(n))).map((s) => s.file);
    map[comp] = { stories: used, excluded: exclusions[comp] };
  }
  return { map, exclusions, stories: stories.map((s) => s.file) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { map, exclusions, stories } = coverage();
  const missing = Object.entries(map).filter(([, v]) => !v.stories.length && !v.excluded);
  const stale = Object.keys(exclusions).filter((k) => !map[k] || map[k].stories.length);
  const covered = Object.entries(map).filter(([, v]) => v.stories.length);
  console.log(`${Object.keys(map).length} reusable component files, ${covered.length} with stories, ${Object.keys(exclusions).length} excluded, ${stories.length} story files.`);
  if (missing.length) console.log(`\nNo story and no exclusion (${missing.length}):\n${missing.map(([k]) => `  ${k}`).join('\n')}`);
  if (stale.length) console.log(`\nExclusions that are stale (covered now or no such component) (${stale.length}):\n${stale.map((k) => `  ${k}`).join('\n')}`);
  if (process.argv.includes('--write')) {
    const lines = ['# Storybook coverage', '', 'Generated by `node scripts/storybook-coverage.mjs --write`. Component files of the reusable library mapped to the stories that import them.', '', '| Component | Stories |', '| --- | --- |'];
    for (const [k, v] of Object.entries(map)) lines.push(`| \`${k}\` | ${v.stories.length ? v.stories.map((s) => `\`${s.replace('storybook/', '')}\``).join(', ') : `_not storied: ${v.excluded ?? 'MISSING'}_`} |`);
    fs.writeFileSync(path.join(ROOT, 'storybook/COVERAGE.md'), `${lines.join('\n')}\n`);
    console.log('Wrote storybook/COVERAGE.md');
  }
  process.exit(missing.length || stale.length ? 1 : 0);
}
